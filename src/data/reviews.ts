export const reviewsFor = (opts: { city?: string; treatment?: string; limit?: number }) => {
  let list = reviews;
  if (opts.treatment) {
    const tagged = list.filter((r) => r.tags.includes(opts.treatment!));
    list = tagged.length >= 2 ? tagged : list.filter((r) => r.tags.length > 0);
  }
  if (opts.city) {
    const local = list.filter((r) => r.city === opts.city);
    list = [...local, ...list.filter((r) => r.city !== opts.city)];
  }
  return list.slice(0, opts.limit ?? 8);
};
